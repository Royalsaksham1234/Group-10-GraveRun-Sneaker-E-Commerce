public void setProductPrice(java.math.BigDecimal price) {
    Total.setText(price != null ? "Rs " + price.toPlainString() : "Rs 0");
}
private void updateTotal() {
    int qty = (int) jSpinner1.getValue();
    double total = unitPrice * qty;
    NumberFormat nf = NumberFormat.getInstance();
    Total.setText("Rs. " + nf.format(total));
}
private void makeSpinnerNonEditable() {
    javax.swing.JComponent editor = jSpinner1.getEditor();
    if (editor instanceof javax.swing.JSpinner.DefaultEditor) {
        javax.swing.JTextField tf =
            ((javax.swing.JSpinner.DefaultEditor) editor).getTextField();
        tf.setEditable(false);
    }
}

