    private void ConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ConfirmActionPerformed

 int qty = (int) jSpinner1.getValue();
    String address = Address.getText().trim();
    String phone = Phone.getText().trim();

    if (address.isEmpty()
            || phone.isEmpty()
            || address.equals("Enter your Address")
            || phone.equals("Enter your Phone Number")) {

        JOptionPane.showMessageDialog(this,
                "Please enter address and phone number",
                "Missing Info",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

try {
    // No need to convert to long anymore!
    String url = StripeService.checkoutSingle(
        product.getName(),
        product.getPrice()           // ← pass BigDecimal directly
    );

    java.awt.Desktop.getDesktop().browse(new java.net.URI(url));
} catch (StripeException e) {
    e.printStackTrace();
    JOptionPane.showMessageDialog(this,
        "Payment initiation failed: " + e.getMessage(),
        "Stripe Error",
        JOptionPane.ERROR_MESSAGE);
} catch (Exception e) {  // for URI/IOException
    e.printStackTrace();
    JOptionPane.showMessageDialog(this,
        "Failed to open payment page",
        "Error",
        JOptionPane.ERROR_MESSAGE);
}



    }//GEN-LAST:event_ConfirmActionPerformed

